package gen_test

import (
	"io/fs"
	"path/filepath"
	"testing"

	"go.dokimi.dev/assert"
	"go.dokimi.dev/assert/files"

	"go.dokimi.dev/spec/internal/gen"
)

// table is a naming table with two sections, whose identifiers are out of
// the order of their names.
const table = `{
  "names": {
    "stances": {"silent": {"go": "Silent", "typescript": "silent"}},
    "claims": {
      "xss-safe": {"go": "XSSSafe", "typescript": "xssSafe"},
      "cache": {"go": "Cache", "typescript": "cache"}
    }
  },
  "languages": ["go", "typescript"]
}
`

func TestGen(t *testing.T) {
	t.Parallel()

	t.Run("Generate", func(t *testing.T) {
		t.Parallel()

		t.Run("writes a constant for each identifier with its Go spelling and the type of its section",
			func(t *testing.T) {
				t.Parallel()
				dir := files.Workspace(t, files.Tree{"naming.json": files.Text(table)})

				assert.NoError(t, gen.Generate(dir), "the table generates")

				got := files.Read(t, filepath.Join(dir, "names.gen.go"))
				assert.HasPrefix(t, got, "// Copyright Dokimasia B.V. 2026\n// SPDX-License-Identifier: MIT\n\n"+
					"// Code generated by spec/internal/gen. DO NOT EDIT.\n\npackage spec\n",
					"the file opens with its header and the package spec")
				assert.Matches(t, got, `XSSSafe +ClaimID += "xss-safe"`, "the claim keeps the spelling of the table")
				assert.Matches(t, got, `Silent +StanceID += "silent"`, "the stance has the type of its section")
				assert.ContainsInOrder(t, got, []string{"Cache", "XSSSafe", "Silent"},
					"the sections and their identifiers are in the order of their names")
			})

		tests := []struct {
			name     string
			giveTree files.Tree
			wantErr  string
		}{
			{
				name:     "returns an error for a table that does not decode",
				giveTree: files.Tree{"naming.json": files.Text("{")},
				wantErr:  "naming.json:",
			},
			{
				name: "returns an error for a section without a Go type",
				giveTree: files.Tree{"naming.json": files.Text(
					`{"names": {"rules": {"r": {"go": "R"}}}}`,
				)},
				wantErr: "the section rules has no Go type",
			},
			{
				name: "returns an error for an identifier without a Go spelling",
				giveTree: files.Tree{"naming.json": files.Text(
					`{"names": {"claims": {"cache": {"typescript": "cache"}}}}`,
				)},
				wantErr: "the identifier cache has no Go spelling",
			},
			{
				name: "returns an error for a Go spelling that is no identifier",
				giveTree: files.Tree{"naming.json": files.Text(
					`{"names": {"claims": {"cache": {"go": "1 cache"}}}}`,
				)},
				wantErr: "names.gen.go:",
			},
			{
				name: "returns an error for names.gen.go that it cannot write",
				giveTree: files.Tree{
					"naming.json":       files.Text(table),
					"names.gen.go/keep": files.Text("a directory in place of the file\n"),
				},
				wantErr: "names.gen.go:",
			},
		}
		for _, tt := range tests {
			t.Run(tt.name, func(t *testing.T) {
				t.Parallel()
				dir := files.Workspace(t, tt.giveTree)

				err := gen.Generate(dir)

				assert.HasError(t, err, "the generation fails")
				assert.Contains(t, err.Error(), tt.wantErr, "the error names the cause")
			})
		}

		t.Run("returns an error for a table that is missing", func(t *testing.T) {
			t.Parallel()
			dir := files.Workspace(t, files.Tree{})

			err := gen.Generate(dir)

			assert.ErrorIs(t, err, fs.ErrNotExist, "the missing table fails the generation")
		})

		t.Run("returns an error for a directory that does not exist", func(t *testing.T) {
			t.Parallel()

			err := gen.Generate(filepath.Join(t.TempDir(), "missing"))

			assert.ErrorIs(t, err, fs.ErrNotExist, "the missing directory fails the generation")
		})
	})
}
