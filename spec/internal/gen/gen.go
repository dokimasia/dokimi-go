// Package gen writes the constants of the package spec from the naming table
// of the vendored copy of the conformance spec.
package gen

import (
	"encoding/json"
	"errors"
	"fmt"
	"go/format"
	"maps"
	"os"
	"slices"
	"strings"
)

// types contains the Go type of the identifiers of each section of the
// naming table.
var types = map[string]string{
	"laws":        "LawID",
	"claims":      "ClaimID",
	"gates":       "GateID",
	"probes":      "ProbeID",
	"reasons":     "ReasonID",
	"forms":       "DefectFormID",
	"machineries": "MachineryID",
	"stances":     "StanceID",
}

// header is the start of names.gen.go, up to the first constant.
const header = `// Copyright Dokimasia B.V. 2026
// SPDX-License-Identifier: MIT

// Code generated by spec/internal/gen. DO NOT EDIT.

package spec

// The identifiers of the entries of the spec.
const (
`

// Generate writes names.gen.go in dir with a constant for each identifier of
// the naming table dir/naming.json. Each constant has the Go spelling of the
// table and the Go type of its section. The sections and the identifiers of
// each section are in the order of their names.
//
// # Errors
//
// Generate returns an error for a table that it cannot read or decode, for
// a section without a Go type, for an identifier without a Go spelling, and
// for a file that it cannot write.
func Generate(dir string) (err error) {
	root, err := os.OpenRoot(dir)
	if err != nil {
		return fmt.Errorf("open the directory of the spec: %w", err)
	}
	defer func() { err = errors.Join(err, root.Close()) }()
	data, err := root.ReadFile("naming.json")
	if err != nil {
		return fmt.Errorf("naming.json: %w", err)
	}
	var table struct {
		Names map[string]map[string]map[string]string `json:"names"`
	}
	if err = json.Unmarshal(data, &table); err != nil {
		return fmt.Errorf("naming.json: %w", err)
	}
	var b strings.Builder
	b.WriteString(header)
	for _, section := range slices.Sorted(maps.Keys(table.Names)) {
		goType, ok := types[section]
		if !ok {
			return fmt.Errorf("naming.json: the section %s has no Go type", section)
		}
		ids := table.Names[section]
		for _, id := range slices.Sorted(maps.Keys(ids)) {
			name := ids[id]["go"]
			if name == "" {
				return fmt.Errorf("naming.json: the identifier %s has no Go spelling", id)
			}
			fmt.Fprintf(&b, "\t%s %s = %q\n", name, goType, id)
		}
	}
	b.WriteString(")\n")
	src, err := format.Source([]byte(b.String()))
	if err == nil {
		err = root.WriteFile("names.gen.go", src, 0o600)
	}
	if err != nil {
		return fmt.Errorf("names.gen.go: %w", err)
	}
	return nil
}
